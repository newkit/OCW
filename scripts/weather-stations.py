#!/usr/bin/env python3
"""Regenerates crates/ocw-weather/src/real/stations.rs (spec §14 Phase 9,
S7): the weather stations of the regional providers.

- MeteoSwiss: the SwissMetNet stations of the open data
  (ogd-smn_meta_stations.csv; CC BY 4.0, "Source: MeteoSwiss").
- DWD: the German stations (WMO block 10) that have current observations
  in opendata.dwd.de/weather/weather_reports/poi/ ("POI" reports), with
  their positions from the MOSMIX station catalogue (degrees and minutes;
  DWD open data, "Source: Deutscher Wetterdienst").

Run from the repository root:  python3 scripts/weather-stations.py
(downloads three small files; the game itself never needs this script).
"""

import re
import sys
import urllib.request
from pathlib import Path

UA = {"User-Agent": "OpenCyclingWorld-station-table/1.0"}
SMN = "https://data.geo.admin.ch/ch.meteoschweiz.ogd-smn/ogd-smn_meta_stations.csv"
POI = "https://opendata.dwd.de/weather/weather_reports/poi/"
CATALOGUE = ("https://www.dwd.de/DE/leistungen/met_verfahren_mosmix/"
             "mosmix_stationskatalog.cfg?view=nasPublication")
OUT = Path("crates/ocw-weather/src/real/stations.rs")


def get(url: str) -> bytes:
    with urllib.request.urlopen(urllib.request.Request(url, headers=UA), timeout=60) as r:
        return r.read()


def deg_min(v: float) -> float:
    """47.53 (47° 53') -> 47.883."""
    sign = -1.0 if v < 0 else 1.0
    v = abs(v)
    d = int(v)
    return sign * (d + round((v - d) * 100.0) / 60.0)


def rust_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main() -> int:
    smn = get(SMN).decode("latin-1").splitlines()
    head = smn[0].split(";")
    col = {name: i for i, name in enumerate(head)}
    swiss = []
    for line in smn[1:]:
        f = line.split(";")
        if len(f) < len(head):
            continue
        swiss.append((
            f[col["station_abbr"]],
            f[col["station_name"]],
            float(f[col["station_coordinates_wgs84_lat"]]),
            float(f[col["station_coordinates_wgs84_lon"]]),
            float(f[col["station_height_masl"]] or 0),
        ))
    ids = set(re.findall(r'href="([0-9A-Z]+)-BEOB\.csv"', get(POI).decode("latin-1")))
    german = []
    for i, line in enumerate(get(CATALOGUE).decode("latin-1").splitlines()):
        if i < 2 or len(line) < 46:
            continue
        sid = line[0:5].strip()
        if sid not in ids or not sid.startswith("10"):
            continue
        name = line[11:31].strip().title()
        german.append((sid, name, deg_min(float(line[32:38])), deg_min(float(line[38:46])),
                       float(line[46:].strip() or 0)))
    swiss.sort()
    german.sort()
    out = [
        "//! Weather stations of the regional providers (spec §14 Phase 9, S7),",
        "//! generated by `scripts/weather-stations.py` – do not edit by hand.",
        "//!",
        "//! - [`SWISS`]: MeteoSwiss SwissMetNet (open data, CC BY 4.0, \"Source:",
        "//!   MeteoSwiss\"; `ogd-smn_meta_stations.csv`).",
        "//! - [`GERMAN`]: DWD stations with current observations (POI reports;",
        "//!   positions from the MOSMIX station catalogue; DWD open data, \"Source:",
        "//!   Deutscher Wetterdienst\").",
        "",
        "/// One station: id, name, latitude, longitude (°), height (m).",
        "pub type Station = (&'static str, &'static str, f64, f64, f32);",
        "",
        f"/// {len(swiss)} SwissMetNet stations (Switzerland and Liechtenstein).",
        "pub const SWISS: &[Station] = &[",
    ]
    out += [f"    ({rust_str(a)}, {rust_str(n)}, {la:.5f}, {lo:.5f}, {h:.1f})," for a, n, la, lo, h in swiss]
    out += ["];", "", f"/// {len(german)} DWD stations in Germany with current observations.",
            "pub const GERMAN: &[Station] = &["]
    out += [f"    ({rust_str(a)}, {rust_str(n)}, {la:.4f}, {lo:.4f}, {h:.1f})," for a, n, la, lo, h in german]
    out += ["];", ""]
    OUT.write_text("\n".join(out), encoding="utf-8")
    print(f"{OUT}: {len(swiss)} Swiss, {len(german)} German stations")
    return 0


if __name__ == "__main__":
    sys.exit(main())
